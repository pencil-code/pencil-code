//A particle cannot write to the 27 grid points it influences (several particles would write to the same point),
//so instead every grid point gathers from the particles in the surrounding cells and writes only to itself.
//The particles are copied in cell order to AC_dep_* and AC_par_cell_start/count give the range of each cell.
